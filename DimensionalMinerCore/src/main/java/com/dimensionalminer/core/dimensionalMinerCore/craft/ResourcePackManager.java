package com.dimensionalminer.core.dimensionalMinerCore.craft;

import com.dimensionalminer.core.dimensionalMinerCore.DimensionalMinerCore;
import com.sun.net.httpserver.HttpServer;
import net.kyori.adventure.text.Component;
import net.kyori.adventure.text.format.NamedTextColor;
import org.bukkit.Bukkit;
import org.bukkit.entity.Player;
import org.bukkit.event.EventHandler;
import org.bukkit.event.Listener;
import org.bukkit.event.player.PlayerJoinEvent;
import org.bukkit.event.player.PlayerQuitEvent;
import org.bukkit.event.player.PlayerResourcePackStatusEvent;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.Enumeration;
import java.util.HexFormat;
import java.util.List;
import java.util.Set;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;
import java.util.zip.ZipOutputStream;

/**
 * Builds the UI resource pack from the jar's {@code pack/} folder (generated by
 * tools/resourcepack/generate.mjs), serves it over a tiny HTTP server and sends it to players on
 * join. Menus ask {@link #hasPack(Player)} and fall back to plain chest items when a player has not
 * (yet) loaded it, so the game stays usable without the pack.
 * <p>
 * config.yml: {@code resource_pack.enabled}, {@code .port} (default 8085), {@code .public_url}
 * (what clients download from; default http://localhost:&lt;port&gt;/pack.zip, fine for local tests),
 * {@code .required}.
 */
public final class ResourcePackManager implements Listener {

    private static final UUID PACK_ID = UUID.nameUUIDFromBytes("dimensionalminer:ui".getBytes(StandardCharsets.UTF_8));

    private final DimensionalMinerCore plugin;
    private final Set<UUID> loaded = ConcurrentHashMap.newKeySet();
    private HttpServer server;
    private byte[] zip;
    private byte[] sha1;
    private String url;
    private boolean required;

    public ResourcePackManager(DimensionalMinerCore plugin) {
        this.plugin = plugin;
    }

    public void start(File pluginJar) {
        var cfg = plugin.getConfig();
        if (!cfg.getBoolean("resource_pack.enabled", true)) {
            plugin.getLogger().info("[Pack] Resource pack disabled in config; menus use plain items.");
            return;
        }
        try {
            zip = buildZip(pluginJar);
            sha1 = MessageDigest.getInstance("SHA-1").digest(zip);
        } catch (Exception e) {
            plugin.getLogger().severe("[Pack] Could not build the resource pack: " + e.getMessage());
            return;
        }
        int port = cfg.getInt("resource_pack.port", 8085);
        String hash = HexFormat.of().formatHex(sha1);
        String base = cfg.getString("resource_pack.public_url", "");
        url = (base == null || base.isBlank() ? "http://localhost:" + port + "/pack.zip" : base) + "?h=" + hash.substring(0, 12);
        required = cfg.getBoolean("resource_pack.required", false);
        try {
            server = HttpServer.create(new InetSocketAddress(port), 0);
            server.createContext("/pack.zip", ex -> {
                ex.getResponseHeaders().add("Content-Type", "application/zip");
                ex.sendResponseHeaders(200, zip.length);
                try (OutputStream os = ex.getResponseBody()) { os.write(zip); }
            });
            server.start();
            plugin.getLogger().info("[Pack] Serving UI pack (" + zip.length / 1024 + " KiB, sha1 " + hash.substring(0, 12) + ") at " + url);
        } catch (IOException e) {
            plugin.getLogger().severe("[Pack] Could not start the pack server on port " + port + ": " + e.getMessage());
            zip = null;
            return;
        }
        for (Player p : Bukkit.getOnlinePlayers()) send(p);
    }

    public void stop() {
        if (server != null) server.stop(0);
        server = null;
    }

    public boolean isEnabled() {
        return zip != null;
    }

    /** True once the client reported the pack as loaded. */
    public boolean hasPack(Player player) {
        return zip != null && loaded.contains(player.getUniqueId());
    }

    public void send(Player player) {
        if (zip == null) return;
        player.setResourcePack(PACK_ID, url, sha1,
                Component.text("Dimensional Miner UI (crafting & forge screens)", NamedTextColor.GOLD), required);
    }

    @EventHandler
    public void onJoin(PlayerJoinEvent event) {
        Player p = event.getPlayer();
        Bukkit.getScheduler().runTaskLater(plugin, () -> { if (p.isOnline()) send(p); }, 20L);
    }

    @EventHandler
    public void onQuit(PlayerQuitEvent event) {
        loaded.remove(event.getPlayer().getUniqueId());
    }

    @EventHandler
    public void onStatus(PlayerResourcePackStatusEvent event) {
        if (!PACK_ID.equals(event.getID())) return;
        switch (event.getStatus()) {
            case SUCCESSFULLY_LOADED -> loaded.add(event.getPlayer().getUniqueId());
            case DECLINED, FAILED_DOWNLOAD, FAILED_RELOAD, INVALID_URL, DISCARDED -> {
                loaded.remove(event.getPlayer().getUniqueId());
                plugin.getLogger().info("[Pack] " + event.getPlayer().getName() + ": " + event.getStatus());
            }
            default -> { }
        }
    }

    /** Zips every jar entry under pack/ (paths relative to pack/). */
    private static byte[] buildZip(File jar) throws IOException {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        int files = 0;
        try (ZipFile in = new ZipFile(jar); ZipOutputStream out = new ZipOutputStream(bytes)) {
            List<ZipEntry> entries = new ArrayList<>();
            for (Enumeration<? extends ZipEntry> e = in.entries(); e.hasMoreElements(); ) {
                ZipEntry z = e.nextElement();
                if (!z.isDirectory() && z.getName().startsWith("pack/")) entries.add(z);
            }
            entries.sort((a, b) -> a.getName().compareTo(b.getName())); // stable order → stable hash
            for (ZipEntry z : entries) {
                ZipEntry o = new ZipEntry(z.getName().substring("pack/".length()));
                o.setTime(0);
                out.putNextEntry(o);
                try (InputStream is = in.getInputStream(z)) { is.transferTo(out); }
                out.closeEntry();
                files++;
            }
        }
        if (files == 0) throw new IOException("no pack/ files in the plugin jar (run tools/resourcepack/generate.mjs)");
        return bytes.toByteArray();
    }
}
